# Engine — SQLite for local dev, swap the URL for Postgres in production
# ---------------------------------------------------------------------

engine = create_engine("sqlite:///cert_prep.db", echo=False)


def create_db_and_tables():
    SQLModel.metadata.create_all(engine)


# ---------------------------------------------------------------------
# THE FIX: build answer_history for analyze_weak_spots() from real data.
# This replaces the toy answer_history list in the demo at the bottom
# of gemini_integration_example.py.
# ---------------------------------------------------------------------

def get_answer_history_for_user(session: Session, user_id: int) -> list[dict]:
    """Returns the shape analyze_weak_spots() expects. Every entry's
    question_type comes from the actual Question row via the join —
    never inferred from the concept string."""
    statement = select(Attempt).where(Attempt.user_id == user_id)
    attempts = session.exec(statement).all()

    now = datetime.now(timezone.utc).replace(tzinfo=None)
    history = []
    for attempt in attempts:
        question = attempt.question
        for concept in question.concept_tags:
            history.append({
                "concept": concept,
                "correct": attempt.is_correct,
                "days_ago": (now - attempt.answered_at).days,
                "question_type": question.question_type.value,
            })
    return history


# ---------------------------------------------------------------------
# Question selection — this is where adaptivity now lives. It moved out
# of generation (which is offline and batched) into selection, which is
# per-user and instant. Same value to the user, no API call.
# ---------------------------------------------------------------------

def select_next_question(
    session: Session,
    user_id: int,
    certification: str,
    weak_concepts: Optional[list[str]] = None,
) -> Optional[Question]:
    """Pick the next question for a user from the approved bank.

    Rules, in order:
      1. Only approved questions for this certification.
      2. Never repeat one the user has already answered.
      3. Prefer questions tagged with the user's weak concepts.
    Returns None when the bank is exhausted for this user."""
    answered_ids = {
        a.question_id
        for a in session.exec(select(Attempt).where(Attempt.user_id == user_id)).all()
    }

    statement = select(Question).where(
        Question.certification == certification,
        Question.review_status == ReviewStatus.approved,
    )
    candidates = [q for q in session.exec(statement).all() if q.id not in answered_ids]
    if not candidates:
        return None

    if weak_concepts:
        weak = set(weak_concepts)
        targeted = [q for q in candidates if weak & set(q.concept_tags)]
        if targeted:
            candidates = targeted

    return random.choice(candidates)


